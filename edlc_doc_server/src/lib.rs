//! Library crate for the EDL documentation server. Contains the Leptos app, MCP server, config,
//! and server functions. The binary (`main.rs`) selects between MCP and HTTP (Leptos+axum) modes.

pub mod app;

#[cfg(feature = "ssr")]
pub mod config;
#[cfg(feature = "ssr")]
pub mod mcp;
#[cfg(feature = "ssr")]
pub mod server;

#[cfg(feature = "hydrate")]
#[wasm_bindgen::prelude::wasm_bindgen]
pub fn hydrate() {
    use crate::app::*;
    console_error_panic_hook::set_once();
    leptos::mount::hydrate_body(App);
}
